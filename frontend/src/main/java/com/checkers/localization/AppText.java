    private AppText() { }

    public static AppLanguage language() {
        return AppLanguage.fromCode(PREFERENCES.get(PREFERENCE_KEY, "en"));
    }

    public static void setLanguage(AppLanguage language) {
        if (language == null) {
            throw new IllegalArgumentException("Language cannot be null.");
        }
        PREFERENCES.put(PREFERENCE_KEY, language.code());
    }

    public static List<AppLanguage> languages() {
        return List.of(AppLanguage.values());
    }

    public static String text(String english) {
        return TRANSLATIONS.getOrDefault(language().code(), Map.of())
                .getOrDefault(english, english);
    }

    public static String text(String english, Object... arguments) {
        String translated = text(english);
        return MessageFormat.format(translated, arguments);
    }

    public static void applyOrientation(Parent parent) {
        parent.setNodeOrientation(language() == AppLanguage.ARABIC
                ? NodeOrientation.RIGHT_TO_LEFT : NodeOrientation.LEFT_TO_RIGHT);
    }

    public static ComboBox<AppLanguage> languagePicker(Runnable onChanged) {
        ComboBox<AppLanguage> picker = new ComboBox<>();
        picker.getItems().setAll(languages());
        picker.setConverter(new StringConverter<>() {
            @Override
            public String toString(AppLanguage language) {
                return language == null ? "" : language.displayName();
            }

            @Override
            public AppLanguage fromString(String value) {
                return AppLanguage.byDisplayName().get(value);
            }
        });
        picker.getSelectionModel().select(language());
        picker.setOnAction(event -> {
            AppLanguage selected = picker.getValue();
            if (selected != null && selected != language()) {
                setLanguage(selected);
                onChanged.run();
            }
        });
        return picker;
    }
